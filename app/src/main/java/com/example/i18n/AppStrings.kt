    fun classLabel(classLevel: Int, language: AppLanguage): String {
        return if (language == AppLanguage.BN) {
            val bnDigits = mapOf(
                1 to "১ম", 2 to "২য়", 3 to "৩য়", 4 to "৪র্থ", 5 to "৫ম",
                6 to "৬ষ্ঠ", 7 to "৭ম", 8 to "৮ম", 9 to "৯ম", 10 to "১০ম"
            )
            "${bnDigits[classLevel] ?: classLevel} শ্রেণি"
        } else {
            "Class $classLevel"
        }
    }

